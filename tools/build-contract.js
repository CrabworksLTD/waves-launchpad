#!/usr/bin/env node
/* Compile contracts/*.sol into app/public/evm-<name>.js — the shape the front
 * end already expects from evm-contract.js: bytecode, abi, and a selector map.
 *
 * Settings are pinned to match the drop contract that is already deployed
 * (0.8.28, optimizer 800 runs, evmVersion paris) so every WAVES contract on
 * every chain is built the same way. `paris` matters: it avoids PUSH0, which
 * some chains still do not accept, and costs nothing on the ones that do.
 *
 *   node tools/build-contract.js WavesToken
 *   node tools/build-contract.js            # all of them
 */
"use strict";
const fs = require("fs");
const path = require("path");
const solc = require("solc");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "contracts");
const outDir = path.join(root, "app", "public");

function compile(name) {
  const file = name + ".sol";
  const source = fs.readFileSync(path.join(srcDir, file), "utf8");

  /* Pull in every local import, so a contract can be written in more than one
   * file. solc's import callback is not available through this binding, so the
   * sources are gathered here instead — one level is enough for what we build,
   * and a missing file fails loudly rather than compiling something partial. */
  const sources = { [file]: { content: source } };
  const seen = new Set([file]);
  const queue = [source];
  while (queue.length) {
    const text = queue.pop();
    for (const m of text.matchAll(/import\s*(?:\{[^}]*\}\s*from\s*)?"\.\/([^"]+)"/g)) {
      const dep = m[1];
      if (seen.has(dep)) continue;
      seen.add(dep);
      const body = fs.readFileSync(path.join(srcDir, dep), "utf8");
      sources[dep] = { content: body };
      queue.push(body);
    }
  }

  const input = {
    language: "Solidity",
    sources: sources,
    settings: {
      optimizer: { enabled: true, runs: 800 },
      // see foundry.toml — the launch path needs it, and the browser
      // encodes this ABI by hand so the arguments stay flat
      viaIR: true,
      evmVersion: "paris",
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.methodIdentifiers"] } }
    }
  };

  const out = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (out.errors || []).filter((e) => e.severity === "error");
  if (errors.length) {
    errors.forEach((e) => console.error(e.formattedMessage));
    throw new Error(name + " did not compile");
  }
  (out.errors || []).forEach((e) => console.warn("  warning:", e.formattedMessage.trim().split("\n")[0]));

  const c = out.contracts[file][name];
  if (!c) throw new Error("no contract named " + name + " in " + file);

  const bytecode = "0x" + c.evm.bytecode.object;
  const selectors = {};
  for (const [sig, sel] of Object.entries(c.evm.methodIdentifiers || {})) selectors[sig] = sel;

  const target = path.join(outDir, "evm-" + name.toLowerCase() + ".js");
  const body =
    "// Generated by tools/build-contract.js — do not edit.\n" +
    "// Source: contracts/" + file + ", solc " + solc.version() +
    ", optimizer 800 runs, evm paris.\n" +
    "window.WAVES_" + name.toUpperCase() + " = {\n" +
    "  version: " + JSON.stringify(solc.version()) + ",\n" +
    "  abi: " + JSON.stringify(c.abi) + ",\n" +
    "  selectors: " + JSON.stringify(selectors) + ",\n" +
    "  bytecode: " + JSON.stringify(bytecode) + "\n" +
    "};\n";
  fs.writeFileSync(target, body);

  /* The same bytes, as plain hex, so a fork test can deploy EXACTLY what ships.
   *
   * forge builds its own copy from the same source and settings, and it is 74
   * bytes different — metadata, as far as anyone can tell, which is a phrase
   * that should not appear anywhere near a contract that moves other people's
   * money. Testing this file instead removes the question. */
  const hexDir = path.join(root, "forge-out", "shipped");
  fs.mkdirSync(hexDir, { recursive: true });
  fs.writeFileSync(path.join(hexDir, name + ".hex"), bytecode);

  console.log("  " + name.padEnd(16) +
    (bytecode.length - 2) / 2 + " bytes  ->  " + path.relative(root, target));
  return { name, size: (bytecode.length - 2) / 2 };
}

const want = process.argv.slice(2);
const names = want.length
  ? want
  : fs.readdirSync(srcDir).filter((f) => f.endsWith(".sol")).map((f) => f.replace(/\.sol$/, ""));

console.log("solc " + solc.version());
names.forEach(compile);
