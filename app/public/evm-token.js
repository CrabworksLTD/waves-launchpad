(function () {
  "use strict";
  /* Token launches and curve trading on an EVM chain.
   *
   * The mirror of token.js, which does the same job on Solana against Meteora's
   * DBC. The shape of a launch is deliberately identical — pick a fee rung, name
   * it, optionally buy first, pledge to holders afterwards — so the two sides of
   * the site are one product rather than two.
   *
   * What differs is who owns the curve. On Solana we are a launch PARTNER and
   * Meteora runs the curve; here there is no Meteora, so contracts/WavesCurve.sol
   * is ours. That means:
   *
   *   - one curve contract holds every launch on a chain, so a launch deploys
   *     only the ERC20 and stays cheap
   *   - the fee ladder is enforced on chain by platformVolumeBps(), not by a
   *     config account we signed once
   *   - graduation moves the whole curve into a Uniswap V3 position that no
   *     function in the contract can withdraw
   *
   * No libraries, same as evm-launch.js: ethers and viem are both larger than
   * everything else this page loads combined, and the encoding needed here is a
   * few dozen lines. Calls are hand-encoded and go out through the wallet or the
   * shared reader.
   *
   * ⚠️ WavesCurve is NOT audited. See contracts/WavesCurve.sol.
   */

  // ---------------------------------------------------------------- selectors
  /* Generated by tools/build-contract.js into evm-wavescurve.js. Read from
   * there rather than pasted, so a signature change cannot leave a stale four
   * bytes here quietly calling the wrong function. */
  function curveAbi() {
    var c = window.WAVES_WAVESCURVE;
    if (!c) throw new Error("evm-wavescurve.js did not load");
    return c;
  }

  function sel(sig) {
    var s = curveAbi().selectors[sig];
    if (!s) throw new Error("no selector for " + sig + " — rebuild evm-wavescurve.js");
    return "0x" + s;
  }

  /* keccak("Launched(address,address,uint16,string,string)").
   *
   * A launch does not return its token address to the caller — a transaction
   * has no return value — so the address is read back out of this event in the
   * receipt. Hard-coded because there is no keccak in the browser without
   * pulling in a library, and verified with `cast keccak`; it changes only if
   * the event signature changes, which would also change the ABI below. */
  var LAUNCHED_TOPIC =
    "0xcf74280e4eafa3845516f297991e114213dc6a4c132199d8338fe6ba26b216e4";

  // ------------------------------------------------------------ abi encoding
  function hex32(v) {
    var s = BigInt(v).toString(16);
    if (s.length > 64) throw new Error("value does not fit in a word");
    return "0".repeat(64 - s.length) + s;
  }

  function addr32(a) {
    var s = String(a || "").toLowerCase().replace(/^0x/, "");
    if (!/^[0-9a-f]{40}$/.test(s)) throw new Error("bad address: " + a);
    return "0".repeat(24) + s;
  }

  /* A dynamic string, as ABI wants it: the length in one word, then the bytes
   * right-padded to a multiple of 32. */
  function strTail(s) {
    var bytes = new TextEncoder().encode(String(s == null ? "" : s));
    var body = "";
    for (var i = 0; i < bytes.length; i++) body += bytes[i].toString(16).padStart(2, "0");
    var pad = (64 - (body.length % 64)) % 64;
    return hex32(bytes.length) + body + "0".repeat(pad);
  }

  function words(hex) { return hex.length / 64; }

  /**
   * launch(string name, string symbol, uint16 feeBps, uint256 minTokensOut)
   *
   * Two dynamic arguments, so the head carries offsets rather than values and
   * the strings follow. Offsets are counted from the start of the ARGUMENTS,
   * not from the start of the call — getting that wrong is the classic way to
   * send a transaction that decodes into nonsense and reverts after paying gas.
   */
  function encodeLaunch(name, symbol, feeBps, minTokensOut) {
    var nameTail = strTail(name);
    var symTail = strTail(symbol);
    var head = 4 * 32;                                   // four arguments
    var offName = head;
    var offSym = head + words(nameTail) * 32;
    return sel("launch(string,string,uint16,uint256)") +
      hex32(offName) + hex32(offSym) + hex32(feeBps) + hex32(minTokensOut) +
      nameTail + symTail;
  }

  // ------------------------------------------------------------ abi decoding
  function wordAt(hex, i) {
    var s = String(hex || "").replace(/^0x/, "");
    return s.slice(i * 64, (i + 1) * 64);
  }

  function uintAt(hex, i) { return BigInt("0x" + (wordAt(hex, i) || "0")); }

  function addrAt(hex, i) { return "0x" + wordAt(hex, i).slice(24); }

  /**
   * curves(address) → the whole state of one launch.
   *
   * Seven static fields, one word each — solidity packs them in storage but
   * pads them back out when returning, so nothing here needs to know about the
   * struct's layout.
   */
  function decodeCurve(hex) {
    if (!hex || hex === "0x") return null;
    return {
      creator: addrAt(hex, 0),
      feeBps: Number(uintAt(hex, 1)),
      rewardsBps: Number(uintAt(hex, 2)),
      keeper: addrAt(hex, 3),
      raised: uintAt(hex, 4),
      tokensLeft: uintAt(hex, 5),
      graduated: uintAt(hex, 6) === 1n
    };
  }

  // ------------------------------------------------------------------ wiring
  function chain() {
    var id = (window.BRAND && window.BRAND.evmChainId) || 4663;
    var all = window.MOONPAD_CHAINS || [];
    for (var i = 0; i < all.length; i++) if (all[i].id === id) return all[i];
    throw new Error("chain " + id + " is not in evm-chains.js");
  }

  /* The one curve contract every launch on this chain goes through. Null until
   * it is deployed and recorded — which is deliberate: a launch UI that silently
   * points at address zero would take a creator's gas and give back nothing. */
  function curveAddress() {
    var b = window.BRAND || {};
    var a = (b.evmCurves || {})[chain().id] || b.evmCurve || null;
    if (!a) {
      throw new Error(
        "No bonding curve is deployed on " + chain().name + " yet. " +
        "Deploy contracts/WavesCurve.sol and put its address in brand.js as evmCurves[" +
        chain().id + "].");
    }
    return a;
  }

  function provider() {
    var p = window.ethereum;
    if (!p) throw new Error("No wallet found in this browser.");
    return p;
  }

  function read(data, to) {
    return window.MoonpadRPC.send(chain().rpc, "eth_call",
      [{ to: to || curveAddress(), data: data }, "latest"]);
  }

  /* Send through the wallet, estimating first. A revert caught by the estimate
   * is free; the same revert on chain costs the whole gas limit and leaves the
   * creator with nothing to show for it. */
  async function send(from, tx) {
    tx.from = from;
    try {
      var gas = await provider().request({ method: "eth_estimateGas", params: [tx] });
      tx.gas = "0x" + ((BigInt(gas) * 12n) / 10n).toString(16);       // 20% headroom
    } catch (e) {
      throw new Error(reason(e));
    }
    await priceTx(tx);
    return provider().request({ method: "eth_sendTransaction", params: [tx] });
  }

  /* EIP-1559, same reasoning as evm-launch.js: a flat gasPrice read a moment
   * ago is rejected the instant the base fee ticks up, and omitting the field
   * makes at least one wallet offer a literal zero. */
  async function priceTx(tx) {
    try {
      var block = await provider().request({ method: "eth_getBlockByNumber", params: ["latest", false] });
      var base = BigInt((block && block.baseFeePerGas) || 0);
      if (base > 0n) {
        var tip = 0n;
        try { tip = BigInt(await provider().request({ method: "eth_maxPriorityFeePerGas", params: [] })); }
        catch (e) {}
        if (tip <= 0n) tip = base / 10n + 1n;
        tx.maxPriorityFeePerGas = "0x" + tip.toString(16);
        tx.maxFeePerGas = "0x" + (base * 3n + tip).toString(16);
        return tx;
      }
      var gp = BigInt(await provider().request({ method: "eth_gasPrice", params: [] }));
      if (gp > 0n) tx.gasPrice = "0x" + (gp * 2n).toString(16);
    } catch (e) {}
    return tx;
  }

  /* Turn a node's revert into something a person can act on. The custom errors
   * in WavesCurve are four bytes on the wire, so without this a creator picking
   * an unlisted fee sees "execution reverted" and has no idea why. */
  /* ⚠️ Computed with `cast keccak "<Name>()"`, never guessed. Written out by
   * hand once and every one of them was wrong — two collided with a real
   * selector by chance, which is the worst case: a plausible, confident, wrong
   * message in front of someone whose transaction just failed. */
  var ERRORS = {
    "0x917f1a53": "That fee tier is not one of the rungs.",
    "0x8698bf37": "That token was not launched here.",
    "0xe6a0d45f": "That token has already graduated — trade it on its pool instead.",
    "0xd66173a5": "The curve has not reached its graduation threshold yet.",
    "0x797dba54": "Nothing is owed to you.",
    "0x7dd37f70": "The price moved past your slippage limit.",
    "0x1f2a2005": "Amount cannot be zero.",
    "0x90b8ec18": "A token transfer failed.",
    "0x93687c0b": "Only the token's creator can do that.",
    "0xb0ca2ff5": "Rewards are already pledged, and a pledge cannot be changed.",
    "0xd98e1888": "The curve is full — it has to graduate before it can take more."
  };

  function reason(e) {
    var msg = (e && (e.message || e.data || "")) + "";
    for (var k in ERRORS) if (msg.indexOf(k) !== -1) return ERRORS[k];
    var m = msg.match(/reverted[^:]*:?\s*(.*)$/i);
    return "The transaction would fail: " + ((m && m[1]) || msg).slice(0, 200);
  }

  // ------------------------------------------------------------------ launch
  /**
   * Open a curve, and optionally buy on the same transaction.
   *
   * The dev buy rides along rather than being a second transaction, which is
   * what closes the window a sniper would otherwise have between the curve
   * opening and the creator's first buy — the same reason the Solana side folds
   * its first buy into pool creation.
   *
   * Rewards are NOT pledged here. On Solana, naming our keeper inside the
   * launch transaction made it require a signature from an address the creator
   * had never seen and Phantom blocked the whole thing as a possible drainer;
   * the same shape is available to any wallet's heuristics on this chain, and
   * the same answer works — pledge afterwards, from the fee page.
   */
  async function launch(opts) {
    opts = opts || {};
    var from = opts.from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);

    var value = BigInt(opts.devBuyWei || 0);
    var data = encodeLaunch(opts.name, opts.symbol, opts.feeBps, opts.minTokensOut || 0);

    var hash = await send(from, {
      to: curveAddress(),
      data: data,
      value: "0x" + value.toString(16)
    });
    return { hash: hash, chain: chain() };
  }

  /**
   * Wait for a launch and dig the new token's address out of the receipt.
   *
   * A dropped poll is not a failed launch: the transaction is signed, paid for
   * and very likely mined, so a blip means ask again. Only running out of
   * attempts is a real timeout.
   */
  async function waitForLaunch(hash) {
    var c = chain();
    for (var i = 0; i < 120; i++) {
      var res = await window.MoonpadRPC.send(c.rpc, "eth_getTransactionReceipt", [hash])
        .catch(function () { return null; });
      if (res) {
        if (res.status === "0x0") throw new Error("The launch transaction reverted");
        var logs = res.logs || [];
        for (var j = 0; j < logs.length; j++) {
          var lg = logs[j];
          if (!lg.topics || lg.topics.length < 3) continue;
          if (String(lg.topics[0]).toLowerCase() !== LAUNCHED_TOPIC) continue;
          // topic1 is the token, topic2 the creator — both indexed
          var token = "0x" + String(lg.topics[1]).replace(/^0x/, "").slice(24);
          return {
            token: token,
            creator: "0x" + String(lg.topics[2]).replace(/^0x/, "").slice(24),
            explorer: c.explorer + "/address/" + token,
            hash: hash
          };
        }
        /* Mined, succeeded, and no Launched event — which should be impossible.
         * Say so plainly rather than returning an undefined address that the
         * page would then try to list. */
        throw new Error("The launch succeeded but no token address was in the receipt.");
      }
      await new Promise(function (r) { setTimeout(r, 2500); });
    }
    throw new Error("Still not confirmed after five minutes — check the explorer");
  }

  // ------------------------------------------------------------------- trade
  async function buy(token, wei, minTokensOut, from) {
    from = from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);
    return send(from, {
      to: curveAddress(),
      data: sel("buy(address,uint256)") + addr32(token) + hex32(minTokensOut || 0),
      value: "0x" + BigInt(wei).toString(16)
    });
  }

  async function sell(token, amount, minWeiOut, from) {
    from = from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);
    return send(from, {
      to: curveAddress(),
      data: sel("sell(address,uint256,uint256)") +
        addr32(token) + hex32(amount) + hex32(minWeiOut || 0),
      value: "0x0"
    });
  }

  /* Selling needs the curve to be allowed to move the seller's tokens, which is
   * a separate transaction on this chain — there is no "sign once" here the way
   * a Solana transfer needs no allowance. Checked first so a creator is not
   * asked to approve when they already have. */
  async function allowance(token, owner) {
    var data = "0xdd62ed3e" + addr32(owner) + addr32(curveAddress());
    var out = await read(data, token);
    return uintAt(out, 0);
  }

  async function approve(token, amount, from) {
    from = from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);
    return send(from, {
      to: token,
      data: "0x095ea7b3" + addr32(curveAddress()) + hex32(amount),
      value: "0x0"
    });
  }

  async function claim(from) {
    from = from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);
    return send(from, { to: curveAddress(), data: sel("claim()"), value: "0x0" });
  }

  /**
   * Pledge a share of the creator's fees to holders. One way, and deliberately
   * its own transaction — see the note on launch().
   */
  async function pledgeToHolders(token, bps, keeper, from) {
    from = from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);
    return send(from, {
      to: curveAddress(),
      data: sel("pledgeToHolders(address,uint16,address)") +
        addr32(token) + hex32(bps) + addr32(keeper),
      value: "0x0"
    });
  }

  /* Permissionless: the threshold is a fact about the chain, so anyone may push
   * the button once it is true. Leaving it to us would mean a token that has met
   * its terms waits on our keeper being awake. */
  async function graduate(token, from) {
    from = from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);
    return send(from, {
      to: curveAddress(),
      data: sel("graduate(address)") + addr32(token),
      value: "0x0"
    });
  }

  // -------------------------------------------------------------------- read
  async function curveOf(token) {
    return decodeCurve(await read(sel("curves(address)") + addr32(token)));
  }

  async function quoteBuy(token, wei) {
    return uintAt(await read(sel("quoteBuy(address,uint256)") + addr32(token) + hex32(wei)), 0);
  }

  async function quoteSell(token, amount) {
    return uintAt(await read(sel("quoteSell(address,uint256)") + addr32(token) + hex32(amount)), 0);
  }

  async function progressBps(token) {
    return Number(uintAt(await read(sel("progressBps(address)") + addr32(token)), 0));
  }

  async function ready(token) {
    return uintAt(await read(sel("ready(address)") + addr32(token)), 0) === 1n;
  }

  async function owed(who) {
    return uintAt(await read(sel("owed(address)") + addr32(who)), 0);
  }

  async function poolOf(token) {
    var a = addrAt(await read(sel("poolOf(address)") + addr32(token)), 0);
    return /^0x0{40}$/.test(a) ? null : a;
  }

  async function balanceOf(token, who) {
    return uintAt(await read("0x70a08231" + addr32(who), token), 0);
  }

  /* The curve's own terms, read from the contract rather than assumed. The
   * numbers a launch page quotes — where it opens, where it graduates — come
   * from here, so a curve deployed with different parameters cannot be
   * described by a page using last month's constants. */
  async function terms() {
    var g = uintAt(await read(sel("graduationEth()")), 0);
    var ve = uintAt(await read(sel("virtualEth()")), 0);
    var vt = uintAt(await read(sel("virtualTokens()")), 0);
    var cs = uintAt(await read(sel("curveSupply()")), 0);
    return { graduationEth: g, virtualEth: ve, virtualTokens: vt, curveSupply: cs };
  }

  // ------------------------------------------------------------------ deploy
  /**
   * Deploy the curve itself. One transaction, once per chain, by us.
   *
   * Here rather than in a script because the deployer has to be a wallet we
   * control and the constructor arguments are the launchpad's whole economics —
   * they are immutable afterwards, there is no owner and no setter, so this is
   * the only moment they can be chosen. Worth doing somewhere the values are
   * visible and checkable rather than buried in a shell command.
   */
  async function deployCurve(opts, from) {
    var art = curveAbi();
    from = from || await window.MoonpadLaunch.connect();
    await window.MoonpadLaunch.switchChain(chain().id);

    var args =
      addr32(opts.platform) +
      hex32(opts.graduationEth) +
      hex32(opts.virtualEth) +
      hex32(opts.virtualTokens) +
      hex32(opts.curveSupply) +
      addr32(opts.factory) +
      addr32(opts.weth) +
      hex32(opts.poolFee);

    return send(from, { data: art.bytecode + args, value: "0x0" });
  }

  window.MoonpadToken = {
    // launch
    launch: launch,
    waitForLaunch: waitForLaunch,
    // trade
    buy: buy,
    sell: sell,
    approve: approve,
    allowance: allowance,
    claim: claim,
    pledgeToHolders: pledgeToHolders,
    graduate: graduate,
    // read
    curveOf: curveOf,
    quoteBuy: quoteBuy,
    quoteSell: quoteSell,
    progressBps: progressBps,
    ready: ready,
    owed: owed,
    poolOf: poolOf,
    balanceOf: balanceOf,
    terms: terms,
    // setup
    deployCurve: deployCurve,
    curveAddress: function () { try { return curveAddress(); } catch (e) { return null; } },
    chain: chain,
    // exported so they can be tested
    encodeLaunch: encodeLaunch,
    decodeCurve: decodeCurve,
    LAUNCHED_TOPIC: LAUNCHED_TOPIC
  };
})();
