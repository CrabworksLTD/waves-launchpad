(function () {
  "use strict";
  /* Token launches on Meteora's Dynamic Bonding Curve.
   *
   * We are the launch *partner*, not a user of somebody else's launchpad. That
   * means a one-time config key (tools/create-dbc-config.js) that fixes the
   * quote mint, the curve, the fee split and the migration rules — and then
   * every creator launch is a pool against that config.
   *
   * Nobody provides liquidity. The curve is the liquidity, and at the migration
   * threshold Meteora moves it into a real DAMM pool on its own. Both partner
   * and creator keep claiming fees from the locked LP afterwards.
   *
   * Fee split, fixed by the protocol:
   *   20%  Meteora
   *   80%  split partner/creator by creatorTradingFeePercentage on the config
   *
   * The reward routing is the interesting part: claimCreatorTradingFeeToReceiver
   * pays a creator's share straight to an address, so a collection's reward
   * vault can be the receiver and no intermediate custody exists.
   */

  /* ---- reward assets ----
   * What a creator's fees get paid out in. SOL needs no swap; everything else
   * is a Jupiter swap by the keeper before distribution.
   *
   * ⚠️ Every mint here must be checked with getAccountInfo, not by eye and not
   * by length. A one-character typo in the USDC mint below still decoded to a
   * valid 32-byte address and passed every format check — it simply pointed at
   * an account that does not exist. Paying rewards into a wrong mint is
   * unrecoverable. tools/check-mints.js does the on-chain check. */
  var REWARDS = {
    sol:  { label: "SOL",  mint: "So11111111111111111111111111111111111111112", verified: true },
    usdc: { label: "USDC", mint: "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v", verified: true },
    // RWA — every verified tokenised equity and commodity, loaded from the
    // generated list rather than typed. See loadRwa() below.
    rwa:  { label: "Real-world asset", mint: null, verified: false, list: true }
  };

  /* The RWA list is data, not constants. Generated by tools/fetch-rwa.js,
   * which requires Jupiter's verified tag plus an asset-class tag and confirms
   * every mint on chain. Searching Jupiter for "TSLAx" alone returns five
   * tokens with that symbol, four of them pump.fun impostors — so a creator
   * picking a reward asset has to be picking from a verified list, never from
   * search results or a typed ticker.
   *
   * Covers Backed xStocks, Ondo Global Markets and standalone commodity
   * tokens. `kind` is "equity" or "commodity" so a picker can group them. */
  var rwaCache = null;
  function loadRwa() {
    if (!rwaCache) {
      rwaCache = fetch("/rwa.json")
        .then(function (r) { return r.json(); })
        .then(function (j) { return j.tokens || []; })
        .catch(function () { return []; });
    }
    return rwaCache;
  }

  // Commodities only, for a "pay my holders in gold" style choice.
  function loadCommodities() {
    return loadRwa().then(function (list) {
      return list.filter(function (t) { return t.kind === "commodity"; });
    });
  }

  var CLUSTERS = {
    // NOT api.mainnet-beta.solana.com — it 403s browser-origin requests
    "mainnet-beta": "https://solana-rpc.publicnode.com",
    devnet: "https://api.devnet.solana.com",
    localnet: "http://127.0.0.1:8899"
  };

  var dbcMod = null, mxMod = null;
  function dbc() { if (!dbcMod) dbcMod = import("/vendor/dbc.esm.js"); return dbcMod; }
  function mx()  { if (!mxMod)  mxMod  = import("/vendor/metaplex.esm.js"); return mxMod; }

  /* The config key is ours and is created once per quote asset. Without one
   * there is no launchpad — a creator cannot launch into a config that does
   * not exist, which is why this reads from BRAND rather than being derived. */
  function configKey(quote) {
    quote = quote || "sol";
    var B = window.BRAND || {};
    var cluster = window.Launch ? window.Launch.cluster() : "mainnet-beta";
    var m = B.dbcConfigs || {};
    // cluster-keyed map is the current shape; a flat {sol,usdc} map or the
    // legacy dbcConfig string only ever meant mainnet
    var c = (m[cluster] && m[cluster][quote]) ||
            (cluster === "mainnet-beta" &&
              (typeof m[quote] === "string" && m[quote] ||
               (quote === "sol" ? B.dbcConfig : null))) || null;
    if (!c) throw new Error(
      "No DBC config for " + quote.toUpperCase() + " on " + cluster +
      ". Run tools/create-dbc-config.js with QUOTE=" + quote +
      ", then put the address in brand.js dbcConfigs[cluster]." + quote + ".");
    return c;
  }

  // which quote currencies this deployment can actually launch in
  function quotes() {
    var out = [];
    try { configKey("sol"); out.push("sol"); } catch (e) {}
    try { configKey("usdc"); out.push("usdc"); } catch (e) {}
    return out;
  }

  /* The locked economics of a quote's config, read from chain rather than
   * hardcoded — display copy that drifts from the real config is worse than
   * none. Falls back to null and the UI says "shown at launch". */
  async function describeConfig(quote) {
    try {
      var M = await dbc(), X = await mx();
      var cluster = window.Launch ? window.Launch.cluster() : "mainnet-beta";
      var conn = new X.Connection(CLUSTERS[cluster] || CLUSTERS["mainnet-beta"], "confirmed");
      var cli = new M.DynamicBondingCurveClient(conn, "confirmed");
      var cfg = await cli.state.getPoolConfig(new X.PublicKey(configKey(quote)));
      var dec = quote === "sol" ? 9 : 6;
      return {
        graduation: Number(cfg.migrationQuoteThreshold) / Math.pow(10, dec),
        feePct: Number(cfg.poolFees.baseFee.cliffFeeNumerator) / 1e7,
        creatorShare: Number(cfg.creatorTradingFeePercentage)
      };
    } catch (e) { return null; }
  }

  async function client() {
    var w = window.Wallet.current();
    if (!w) throw new Error("Connect a wallet first");
    var M = await dbc(), X = await mx();
    var cluster = window.Launch ? window.Launch.cluster() : "mainnet-beta";
    // web3.js Connection, which is what the DBC SDK expects — it predates umi
    // and takes a raw connection plus signers rather than an identity.
    var conn = new X.Connection(CLUSTERS[cluster] || CLUSTERS["mainnet-beta"], "confirmed");
    return {
      M: M, X: X, conn: conn, wallet: w,
      cli: new M.DynamicBondingCurveClient(conn, "confirmed"),
      owner: new X.PublicKey(w.publicKey)
    };
  }

  async function send(c, txish) {
    var tx = txish.transaction ? txish.transaction : txish;
    tx.feePayer = c.owner;
    tx.recentBlockhash = (await c.conn.getLatestBlockhash("confirmed")).blockhash;
    // Extra keypairs the SDK needs to sign for (the new mint, usually) are
    // returned alongside the transaction and have to be applied before the
    // wallet signs, or the wallet's signature covers the wrong message.
    if (txish.signers && txish.signers.length) tx.partialSign.apply(tx, txish.signers);
    var signed = await c.wallet.signTransaction(tx);
    var sig = await c.conn.sendRawTransaction(signed.serialize(), { skipPreflight: false });
    await c.conn.confirmTransaction(sig, "confirmed");
    return sig;
  }

  /* Launch a token. `firstBuySol` > 0 uses createPoolWithFirstBuy so the
   * creator's own buy lands in the same transaction as the pool — otherwise a
   * sniper can be first in line between the two. */
  async function launchToken(opts) {
    var c = await client();
    var progress = opts.onProgress || function () {};

    var baseMint = c.X.Keypair.generate();
    progress({ step: "pool", state: "signing" });

    var args = {
      config: new c.X.PublicKey(configKey(opts.quote)),
      baseMint: baseMint.publicKey,
      name: opts.name,
      symbol: opts.symbol,
      uri: opts.uri,
      payer: c.owner,
      poolCreator: c.owner
    };

    var built;
    if (opts.firstBuySol > 0) {
      built = await c.cli.creator.createPoolWithFirstBuy({
        createPoolParam: args,
        firstBuyParam: {
          buyer: c.owner,
          buyAmount: c.M.convertToLamports(opts.firstBuySol, 9),
          minimumAmountOut: 1,        // creator buying their own launch, slippage is theirs
          referralTokenAccount: null
        }
      });
    } else {
      built = await c.cli.creator.createPool(args);
    }

    var tx = built.createPoolTx || built.transaction || built;
    var sig = await send(c, { transaction: tx, signers: [baseMint] });
    progress({ step: "pool", state: "done", mint: String(baseMint.publicKey) });

    // Record for the homepage token listing — fire-and-forget, same contract
    // as the collections listing: the pool exists regardless.
    fetch("/api/tokens", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        mint: String(baseMint.publicKey), name: opts.name, symbol: opts.symbol,
        rewardMint: opts.rewardMint || null,
        collection: opts.collection || null,
        creator: String(c.owner),
        quote: opts.quote || "sol",
        feeWallet: opts.feeWallet || null,
        cluster: window.Launch ? window.Launch.cluster() : "mainnet-beta"
      })
    }).catch(function () {});

    return {
      mint: String(baseMint.publicKey),
      signature: sig,
      cluster: window.Launch ? window.Launch.cluster() : "mainnet-beta"
    };
  }

  /* Live pool state for a launched token — curve progress, fees earned so far.
   * Read-only, so no wallet needed. */
  async function readPool(baseMint) {
    var M = await dbc(), X = await mx();
    var cluster = window.Launch ? window.Launch.cluster() : "mainnet-beta";
    var conn = new X.Connection(CLUSTERS[cluster] || CLUSTERS["mainnet-beta"], "confirmed");
    var cli = new M.DynamicBondingCurveClient(conn, "confirmed");

    var pool = await cli.state.getPoolByBaseMint(new X.PublicKey(baseMint));
    if (!pool) return null;
    var progress = await cli.state.getPoolQuoteTokenCurveProgress(pool.publicKey)
      .catch(function () { return null; });
    var fees = await cli.state.getPoolFeeMetrics(pool.publicKey)
      .catch(function () { return null; });

    return {
      pool: String(pool.publicKey),
      baseMint: baseMint,
      // 0..1 toward the migration threshold; past 1 it has graduated to DAMM
      curveProgress: progress == null ? null : Number(progress),
      migrated: !!(pool.account &&
        (pool.account.poolState || pool.account).isMigrated),
      fees: fees || null
    };
  }

  /* Claim a creator's accrued trading fees straight into a receiver — the
   * collection's reward vault. This is what makes the rewards loop work without
   * us ever holding creator funds. */
  async function claimCreatorFeesTo(baseMint, receiver) {
    var c = await client();
    var pool = await c.cli.state.getPoolByBaseMint(new c.X.PublicKey(baseMint));
    if (!pool) throw new Error("No pool for that mint");

    // u64 max as BN: "claim everything". The SDK types these as BN, not
    // nullable — null builds an instruction the program rejects.
    var U64MAX = "18446744073709551615";
    var tx = await c.cli.creator.claimCreatorTradingFeeToReceiver({
      creator: c.owner,
      payer: c.owner,
      pool: pool.publicKey,
      receiver: new c.X.PublicKey(receiver),
      maxBaseAmount: new c.M.BN(U64MAX),
      maxQuoteAmount: new c.M.BN(U64MAX)
    });
    return await send(c, tx);
  }

  /* ---- trading, for the /token page ---- */

  async function readCtx(baseMint) {
    var M = await dbc(), X = await mx();
    var cluster = window.Launch ? window.Launch.cluster() : "mainnet-beta";
    var conn = new X.Connection(CLUSTERS[cluster] || CLUSTERS["mainnet-beta"], "confirmed");
    var cli = new M.DynamicBondingCurveClient(conn, "confirmed");
    var pool = await cli.state.getPoolByBaseMint(new X.PublicKey(baseMint));
    if (!pool) throw new Error("No pool for that mint on " + cluster);
    // the decoded state nests one level down as .poolState — but swapQuote
    // wants the WRAPPED object (it reads virtualPool.poolState.* itself)
    var acct = pool.account.poolState || pool.account;
    var vpool = pool.account.poolState ? pool.account : { poolState: pool.account };
    var cfg = await cli.state.getPoolConfig(acct.config);
    // no decimal field on the config for the quote side — it follows the mint
    var quoteDec = String(cfg.quoteMint) === "So11111111111111111111111111111111111111112" ? 9 : 6;
    return { M: M, X: X, conn: conn, cli: cli, pool: pool, acct: acct,
             vpool: vpool, cfg: cfg, quoteDec: quoteDec };
  }

  /* Everything the trading page shows, in one read. Price is quoted from the
   * live curve by pricing a tiny buy — the same maths a real swap uses, so the
   * number cannot drift from what a buyer would actually pay. */
  async function readMarket(baseMint) {
    var c = await readCtx(baseMint);
    var acct = c.acct;
    var quoteDec = c.quoteDec;
    var threshold = Number(c.cfg.migrationQuoteThreshold) / Math.pow(10, quoteDec);
    var raised = Number(acct.quoteReserve) / Math.pow(10, quoteDec);

    var price = null;
    try {
      var probe = new c.M.BN(Math.pow(10, quoteDec - 3)); // 0.001 quote units in
      var slot = await c.conn.getSlot("confirmed");
      var q = c.cli.pool.swapQuote({
        virtualPool: c.vpool, config: c.cfg,
        swapBaseForQuote: false, amountIn: probe,
        slippageBps: 0, hasReferral: false,
        eligibleForFirstSwapWithMinFee: false,
        currentPoint: new c.M.BN(slot)
      });
      var out = Number(q.outputAmount || q.amountOut || 0);
      if (out > 0) price = (0.001) / (out / 1e6);  // quote per token, 6-dec base
    } catch (e) { /* price stays null, page says so */ }

    return {
      pool: String(c.pool.publicKey),
      migrated: !!acct.isMigrated,
      raised: raised,
      threshold: threshold,
      progress: threshold > 0 ? Math.min(1, raised / threshold) : 0,
      price: price,
      quote: quoteDec === 9 ? "SOL" : "USDC",
      creator: String(acct.creator)
    };
  }

  /* A live quote for the trade box. direction "buy" = quote in, base out. */
  async function getQuote(baseMint, amount, direction) {
    var c = await readCtx(baseMint);
    var quoteDec = c.quoteDec;
    var dec = direction === "buy" ? quoteDec : 6;
    var amountIn = new c.M.BN(Math.round(amount * Math.pow(10, dec)));
    var slot = await c.conn.getSlot("confirmed");
    var q = c.cli.pool.swapQuote({
      virtualPool: c.vpool, config: c.cfg,
      swapBaseForQuote: direction !== "buy",
      amountIn: amountIn,
      slippageBps: 100,                            // 1%
      hasReferral: false,
      eligibleForFirstSwapWithMinFee: false,
      currentPoint: new c.M.BN(slot)
    });
    var outRaw = q.outputAmount || q.amountOut || 0;
    var minRaw = q.minimumAmountOut || q.minAmountOut || outRaw;
    var outDec = direction === "buy" ? 6 : quoteDec;
    return {
      out: Number(outRaw) / Math.pow(10, outDec),
      minOut: String(minRaw),
      amountIn: String(amountIn)
    };
  }

  /* Execute the trade with the connected wallet. minOut comes from getQuote so
   * the user was shown the number their slippage floor protects. */
  async function swap(baseMint, direction, amountInRaw, minOutRaw) {
    var c = await client();                        // wallet-connected web3 ctx
    var pool = await c.cli.state.getPoolByBaseMint(new c.X.PublicKey(baseMint));
    if (!pool) throw new Error("No pool for that mint");
    var tx = await c.cli.pool.swap({
      owner: c.owner,
      pool: pool.publicKey,
      amountIn: new c.M.BN(amountInRaw),
      minimumAmountOut: new c.M.BN(minOutRaw),
      swapBaseForQuote: direction !== "buy",
      referralTokenAccount: null
    });
    return await send(c, tx);
  }

  /* The connected wallet's balance of a launch token, in whole tokens.
   * The sell box's percentage chips size against this. */
  async function balanceOf(baseMint) {
    var X = await mx();
    var w = window.Wallet.current();
    if (!w) return null;
    var cluster = window.Launch ? window.Launch.cluster() : "mainnet-beta";
    var conn = new X.Connection(CLUSTERS[cluster] || CLUSTERS["mainnet-beta"], "confirmed");
    var res = await conn.getParsedTokenAccountsByOwner(
      new X.PublicKey(w.publicKey), { mint: new X.PublicKey(baseMint) });
    var total = 0;
    (res.value || []).forEach(function (a) {
      total += a.account.data.parsed.info.tokenAmount.uiAmount || 0;
    });
    return total;
  }

  window.Token = {
    readMarket: readMarket,
    getQuote: getQuote,
    swap: swap,
    balanceOf: balanceOf,
    launchToken: launchToken,
    readPool: readPool,
    claimCreatorFeesTo: claimCreatorFeesTo,
    rewards: REWARDS,
    rwa: loadRwa,
    commodities: loadCommodities,
    quotes: quotes,
    describeConfig: describeConfig,
    configKey: function () { try { return configKey(); } catch (e) { return null; } }
  };
})();
